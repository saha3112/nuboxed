def grouped_modules():
    groups = {}
    for key, config in MODULES.items():
        if key in {"attributes", "pagetext"} or (config.get("group") in {"Operations", "Merchandising"} and key != "inventory"):
            continue
        groups.setdefault(config["group"], []).append((key, config))
    return groups
